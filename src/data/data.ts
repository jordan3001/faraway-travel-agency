const itin = (steps: [string, string][]): ItineraryStep[] =>
  steps.map(([title, description], i) => ({ day: i + 1, title, description }))

const opt = (
  id: string,
  name: string,
  description: string,
  price: number,
  unit: 'person' | 'booking' = 'person',
): TicketOption => ({ id, name, description, price, unit })

const daysAhead = (days: number) => {
  const d = new Date()
  d.setHours(12, 0, 0, 0)
  d.setDate(d.getDate() + days)
  return d.toISOString()
}

