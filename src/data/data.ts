const createSeedBookings = (): Booking[] => {
  const exps = buildExperiences().filter((e) => e.status === 'active')
  const clis = buildClients()
  const source = [...clis, ...clis.slice(0, 5)]
  return seedStatuses.map((status, i) => {
    const exp = exps[i % exps.length]
    const client = source[i % source.length]
    const adults = i % 4 === 0 ? 2 : i % 3 === 0 ? 1 : 2
    const children = i % 5 === 0 ? 2 : i % 3 === 0 ? 0 : 1
    const options = exp.options.slice(0, i % 3).map((o) => o.id)
    const extras = options.reduce((sum, optionId) => {
      const option = exp.options.find((o) => o.id === optionId)
      if (!option) return sum
      return sum + (option.unit === 'person' ? option.price * (adults + children) : option.price)
    }, 0)
    const total = exp.price * adults + exp.childPrice * children + extras
    const createdOffset = -(3 + i * 5)
    const travelOffset =
      status === 'completed'
        ? createdOffset - 30
        : status === 'cancelled'
          ? createdOffset + 16
          : 24 + i * 7
    return {
      id: `bk-${1000 + i}`,
      reference: `FW-${2026}-${1042 + i}`,
      clientId: i === 0 ? 'cli-1' : i === 1 ? 'cli-1' : client.id,
      experienceId: i === 0 ? 'exp-disney' : i === 1 ? 'exp-rome' : exp.id,
      date: daysAhead(travelOffset),
      adults,
      children,
      options,
      total,
      status,
      paymentStatus: status === 'cancelled' ? 'refunded' : status === 'pending' ? 'deposit' : 'paid',
      createdAt: daysAhead(createdOffset),
      channel: i % 7 === 0 ? 'agence' : i % 5 === 0 ? 'téléphone' : 'web',
      notes: i === 0 ? 'Week-end pour notre anniversaire de mariage.' : '',
      internalNotes: i === 0 ? 'Client VIP — offrir un surclassement si disponibilité.' : '',
      promoCode: i % 4 === 0 ? 'FARAWAY10' : undefined,
      supplierId: i === 0 ? 'sup-disney' : i === 1 ? 'sup-roma' : exp.supplierId,
    }
  })
}

